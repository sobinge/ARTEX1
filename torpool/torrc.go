package torpool

import (
	"fmt"
	"path/filepath"
	"strings"
	"time"
)

// torrc renders the configuration for one pool instance.
//
// Each instance is a full Tor daemon with its own DataDirectory, SOCKS port and
// control port. Isolation between agents then comes from two independent
// layers: different daemons (different guards/exit pools) and, inside a shared
// daemon, IsolateSOCKSAuth usernames. Without per-instance daemons a SINGAL
// NEWNYM would rotate every agent's circuits at once — the reason this package
// exists.
func (c Config) torrc(inst Instance) string {
	var b strings.Builder
	line := func(format string, args ...any) {
		fmt.Fprintf(&b, format+"\n", args...)
	}

	line("# generated by artex torpool; do not edit by hand")
	line("DataDirectory %s", inst.DataDir)
	line("SocksPort 127.0.0.1:%d IsolateSOCKSAuth", inst.SocksPort)
	line("ControlPort 127.0.0.1:%d", inst.ControlPort)
	line("CookieAuthentication 1")
	line("CookieAuthFile %s", inst.CookiePath)
	line("ClientOnly 1")
	line("MaxCircuitDirtiness %d", c.MaxCircuitDirtiness)
	line("Log notice file %s", filepath.Join(inst.DataDir, "tor.log"))
	line("AvoidDiskWrites 1")
	line("ConnectionPadding 1")
	if up := strings.TrimSpace(c.UpstreamProxy); up != "" {
		hostport, creds := up, ""
		if at := strings.LastIndex(up, "@"); at >= 0 {
			creds, hostport = up[:at], up[at+1:]
		}
		line("HTTPSProxy %s", hostport)
		if creds != "" {
			line("HTTPSProxyAuthenticator %s", creds)
		}
	}
	if cc := strings.ToLower(strings.TrimSpace(c.ExitCountry)); cc != "" {
		line("ExitNodes {%s}", cc)
		line("StrictNodes 1")
	}
	return b.String()
}

// validate normalises defaults and rejects configurations that cannot work.
// Ports are checked as a set: a SOCKS port that collides with any control port
// would silently make one instance unreachable.
func (c *Config) validate() error {
	if c.Size <= 0 {
		return fmt.Errorf("torpool: size must be >= 1")
	}
	if c.Size > 32 {
		return fmt.Errorf("torpool: size %d is too large (max 32)", c.Size)
	}
	if strings.TrimSpace(c.Dir) == "" {
		return fmt.Errorf("torpool: dir is required")
	}
	if c.SocksBase <= 0 || c.SocksBase > 65535 {
		return fmt.Errorf("torpool: invalid socks base port %d", c.SocksBase)
	}
	if c.ControlBase <= 0 || c.ControlBase > 65535 {
		return fmt.Errorf("torpool: invalid control base port %d", c.ControlBase)
	}
	lastSocks := c.SocksBase + c.Size - 1
	lastControl := c.ControlBase + c.Size - 1
	if lastSocks > 65535 || lastControl > 65535 {
		return fmt.Errorf("torpool: port range exceeds 65535")
	}
	if c.SocksBase <= lastControl && c.ControlBase <= lastSocks {
		return fmt.Errorf("torpool: socks range %d-%d overlaps control range %d-%d",
			c.SocksBase, lastSocks, c.ControlBase, lastControl)
	}
	if strings.TrimSpace(c.Binary) == "" {
		c.Binary = "tor"
	}
	if c.MaxCircuitDirtiness <= 0 {
		c.MaxCircuitDirtiness = 600
	}
	if c.StartupTimeout <= 0 {
		c.StartupTimeout = 45 * time.Second
	}
	return nil
}

// portSummary is used in error messages and status output.
func (c Config) portSummary() string {
	return fmt.Sprintf("socks=%d..%d control=%d..%d",
		c.SocksBase, c.SocksBase+c.Size-1, c.ControlBase, c.ControlBase+c.Size-1)
}
